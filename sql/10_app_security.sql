-- =====================================================================
-- 10_app_security.sql
-- LAYER 4: APPLICATION USERS AND ROLES (role-based access control)
--
-- WHO YOU ARE (authentication) is handled by Oracle APEX itself
-- (APEX Accounts, or Social Sign-In / SSO). We never store passwords here.
-- WHAT YOU MAY DO (authorization) is decided by these tables:
-- APEX "Authorization Schemes" call pkg_security.has_role(:APP_USER, 'ROLE').
--
--   APP_USER  *--< APP_USER_ROLE >--*  APP_ROLE     (many-to-many via a bridge table)
-- =====================================================================
SET DEFINE OFF;

CREATE TABLE app_user (
    user_id                  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    username                 VARCHAR2(100) NOT NULL,   -- must equal the APEX login name (:APP_USER)
    email                    VARCHAR2(120) NOT NULL,
    authentication_provider  VARCHAR2(30) DEFAULT 'APEX_ACCOUNTS' NOT NULL,
    branch_id                NUMBER,                   -- optional: a loan officer's home branch
    is_active                NUMBER(1) DEFAULT 1 NOT NULL,
    created_at               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_app_user          PRIMARY KEY (user_id),
    CONSTRAINT uq_app_user_username UNIQUE (username),
    CONSTRAINT uq_app_user_email    UNIQUE (email),
    CONSTRAINT fk_app_user_branch   FOREIGN KEY (branch_id) REFERENCES branch(branch_id),
    CONSTRAINT ck_app_user_active   CHECK (is_active IN (0,1)),
    CONSTRAINT ck_app_user_upper    CHECK (username = UPPER(username)),   -- APEX gives :APP_USER in upper case
    CONSTRAINT ck_app_user_provider CHECK (authentication_provider IN ('APEX_ACCOUNTS','SSO','SOCIAL_SIGN_IN'))
);

CREATE TABLE app_role (
    role_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    role_name    VARCHAR2(30)  NOT NULL,
    description  VARCHAR2(200),
    CONSTRAINT pk_app_role      PRIMARY KEY (role_id),
    CONSTRAINT uq_app_role_name UNIQUE (role_name)
);

-- bridge table: composite primary key = a user cannot get the same role twice
CREATE TABLE app_user_role (
    user_id      NUMBER NOT NULL,
    role_id      NUMBER NOT NULL,
    assigned_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_app_user_role PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_aur_user FOREIGN KEY (user_id) REFERENCES app_user(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_aur_role FOREIGN KEY (role_id) REFERENCES app_role(role_id)
);
CREATE INDEX ix_aur_role ON app_user_role (role_id);

-- ---------------------------------------------------------------------
-- Security helper used by APEX authorization schemes
-- ---------------------------------------------------------------------
CREATE OR REPLACE PACKAGE pkg_security AS
    FUNCTION has_role (p_username VARCHAR2, p_role_name VARCHAR2) RETURN BOOLEAN;
    FUNCTION has_role_yn (p_username VARCHAR2, p_role_name VARCHAR2) RETURN VARCHAR2;  -- for SQL
END pkg_security;
/

CREATE OR REPLACE PACKAGE BODY pkg_security AS
    FUNCTION has_role_yn (p_username VARCHAR2, p_role_name VARCHAR2) RETURN VARCHAR2 IS
        v_cnt NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_cnt
        FROM   app_user u
        JOIN   app_user_role ur ON ur.user_id = u.user_id
        JOIN   app_role r       ON r.role_id  = ur.role_id
        WHERE  u.username  = UPPER(p_username)
        AND    u.is_active = 1
        AND    r.role_name IN (UPPER(p_role_name), 'ADMIN');   -- ADMIN can do everything
        RETURN CASE WHEN v_cnt > 0 THEN 'Y' ELSE 'N' END;
    END has_role_yn;

    FUNCTION has_role (p_username VARCHAR2, p_role_name VARCHAR2) RETURN BOOLEAN IS
    BEGIN
        RETURN has_role_yn(p_username, p_role_name) = 'Y';
    END has_role;
END pkg_security;
/

