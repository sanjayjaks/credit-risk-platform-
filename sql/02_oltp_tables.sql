-- =====================================================================
-- 02_oltp_tables.sql
-- LAYER 1: OPERATIONAL DATABASE (OLTP)
-- The "live" system of record: customers, branches, loan products,
-- applications, loans and repayments. Optimised for correct, fast
-- day-to-day inserts and updates (normalised, strict constraints).
-- Oracle 19c / 21c / 23ai compatible.
-- =====================================================================

-- ---------------------------------------------------------------------
-- BRANCH: physical offices of the (fictional) lender
-- ---------------------------------------------------------------------
CREATE TABLE branch (
    branch_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    branch_code     VARCHAR2(10)  NOT NULL,           -- code used by source systems, e.g. BR001
    branch_name     VARCHAR2(100) NOT NULL,
    city            VARCHAR2(60)  NOT NULL,
    state           VARCHAR2(60)  NOT NULL,
    branch_manager  VARCHAR2(100),
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_branch       PRIMARY KEY (branch_id),
    CONSTRAINT uq_branch_code  UNIQUE (branch_code)
);

-- ---------------------------------------------------------------------
-- LOAN_TYPE: product catalogue (Personal, Home, Auto ...)
-- ---------------------------------------------------------------------
CREATE TABLE loan_type (
    loan_type_id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    loan_type_name         VARCHAR2(50)  NOT NULL,
    description            VARCHAR2(400),
    interest_rate          NUMBER(5,2)   NOT NULL,     -- annual % e.g. 13.50
    minimum_amount         NUMBER(15,2)  NOT NULL,
    maximum_amount         NUMBER(15,2)  NOT NULL,
    maximum_tenure_months  NUMBER(4)     NOT NULL,
    CONSTRAINT pk_loan_type        PRIMARY KEY (loan_type_id),
    CONSTRAINT uq_loan_type_name   UNIQUE (loan_type_name),
    CONSTRAINT ck_lt_rate          CHECK (interest_rate > 0 AND interest_rate <= 50),
    CONSTRAINT ck_lt_amounts       CHECK (minimum_amount > 0 AND maximum_amount >= minimum_amount),
    CONSTRAINT ck_lt_tenure        CHECK (maximum_tenure_months BETWEEN 1 AND 480)
);

-- ---------------------------------------------------------------------
-- CUSTOMER: borrowers
-- ---------------------------------------------------------------------
CREATE TABLE customer (
    customer_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    source_customer_ref  VARCHAR2(30),                 -- ID in the source CRM file (used by ETL to match)
    first_name           VARCHAR2(50)  NOT NULL,
    last_name            VARCHAR2(50)  NOT NULL,
    date_of_birth        DATE,
    gender               VARCHAR2(1),
    email                VARCHAR2(120) NOT NULL,
    phone                VARCHAR2(15),
    address              VARCHAR2(200),
    city                 VARCHAR2(60),
    state                VARCHAR2(60),
    annual_income        NUMBER(15,2),
    employment_status    VARCHAR2(20),
    credit_score         NUMBER(3),
    customer_since       DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    created_at           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_customer         PRIMARY KEY (customer_id),
    CONSTRAINT uq_customer_email   UNIQUE (email),
    CONSTRAINT uq_customer_srcref  UNIQUE (source_customer_ref),
    CONSTRAINT ck_cust_gender      CHECK (gender IN ('M','F','O')),
    CONSTRAINT ck_cust_income      CHECK (annual_income >= 0),
    CONSTRAINT ck_cust_score       CHECK (credit_score BETWEEN 300 AND 900),
    CONSTRAINT ck_cust_employment  CHECK (employment_status IN
        ('SALARIED','SELF_EMPLOYED','BUSINESS_OWNER','STUDENT','RETIRED','UNEMPLOYED'))
);

-- ---------------------------------------------------------------------
-- LOAN_APPLICATION: a customer's request for a loan
-- Allowed statuses: PENDING -> UNDER_REVIEW -> APPROVED | REJECTED
-- ---------------------------------------------------------------------
CREATE TABLE loan_application (
    application_id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    customer_id              NUMBER        NOT NULL,
    branch_id                NUMBER        NOT NULL,
    loan_type_id             NUMBER        NOT NULL,
    application_date         DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    requested_amount         NUMBER(15,2)  NOT NULL,
    requested_tenure_months  NUMBER(4)     NOT NULL,
    application_status       VARCHAR2(15) DEFAULT 'PENDING' NOT NULL,
    rejection_reason         VARCHAR2(200),
    approved_date            DATE,
    created_at               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_loan_application PRIMARY KEY (application_id),
    CONSTRAINT fk_app_customer  FOREIGN KEY (customer_id)  REFERENCES customer(customer_id),
    CONSTRAINT fk_app_branch    FOREIGN KEY (branch_id)    REFERENCES branch(branch_id),
    CONSTRAINT fk_app_loan_type FOREIGN KEY (loan_type_id) REFERENCES loan_type(loan_type_id),
    CONSTRAINT ck_app_amount    CHECK (requested_amount > 0),
    CONSTRAINT ck_app_tenure    CHECK (requested_tenure_months > 0),
    CONSTRAINT ck_app_status    CHECK (application_status IN ('PENDING','UNDER_REVIEW','APPROVED','REJECTED')),
    -- an approved application must have an approval date; a rejected one must have a reason
    CONSTRAINT ck_app_approved  CHECK (application_status <> 'APPROVED' OR approved_date IS NOT NULL),
    CONSTRAINT ck_app_rejected  CHECK (application_status <> 'REJECTED' OR rejection_reason IS NOT NULL),
    CONSTRAINT ck_app_dates     CHECK (approved_date IS NULL OR approved_date >= application_date)
);

-- ---------------------------------------------------------------------
-- LOAN: an approved application that has been paid out (disbursed)
-- Allowed statuses: ACTIVE, CLOSED (fully repaid), DEFAULTED (90+ days unpaid)
-- application_id is UNIQUE  => one application gives at most one loan (1 : 0..1)
-- ---------------------------------------------------------------------
CREATE TABLE loan (
    loan_id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    source_loan_ref      VARCHAR2(30),                 -- ID in the source loan-management file
    application_id       NUMBER        NOT NULL,
    customer_id          NUMBER        NOT NULL,
    branch_id            NUMBER        NOT NULL,
    loan_type_id         NUMBER        NOT NULL,
    principal_amount     NUMBER(15,2)  NOT NULL,
    interest_rate        NUMBER(5,2)   NOT NULL,        -- rate locked at disbursement
    tenure_months        NUMBER(4)     NOT NULL,
    emi_amount           NUMBER(15,2)  NOT NULL,        -- fixed monthly instalment
    disbursement_date    DATE          NOT NULL,
    maturity_date        DATE          NOT NULL,
    outstanding_balance  NUMBER(15,2)  NOT NULL,        -- CURRENT balance only (history lives in the warehouse)
    loan_status          VARCHAR2(15) DEFAULT 'ACTIVE' NOT NULL,
    closed_date          DATE,
    created_at           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_loan             PRIMARY KEY (loan_id),
    CONSTRAINT uq_loan_application UNIQUE (application_id),
    CONSTRAINT uq_loan_srcref      UNIQUE (source_loan_ref),
    CONSTRAINT fk_loan_application FOREIGN KEY (application_id) REFERENCES loan_application(application_id),
    CONSTRAINT fk_loan_customer    FOREIGN KEY (customer_id)    REFERENCES customer(customer_id),
    CONSTRAINT fk_loan_branch      FOREIGN KEY (branch_id)      REFERENCES branch(branch_id),
    CONSTRAINT fk_loan_loan_type   FOREIGN KEY (loan_type_id)   REFERENCES loan_type(loan_type_id),
    CONSTRAINT ck_loan_principal   CHECK (principal_amount > 0),
    CONSTRAINT ck_loan_rate        CHECK (interest_rate > 0 AND interest_rate <= 50),
    CONSTRAINT ck_loan_tenure      CHECK (tenure_months > 0),
    CONSTRAINT ck_loan_emi         CHECK (emi_amount > 0),
    CONSTRAINT ck_loan_balance     CHECK (outstanding_balance >= 0 AND outstanding_balance <= principal_amount),
    CONSTRAINT ck_loan_dates       CHECK (maturity_date > disbursement_date),
    CONSTRAINT ck_loan_status      CHECK (loan_status IN ('ACTIVE','CLOSED','DEFAULTED')),
    -- a CLOSED loan must have a closed_date, any other status must not
    CONSTRAINT ck_loan_closed      CHECK ((loan_status = 'CLOSED'  AND closed_date IS NOT NULL)
                                       OR (loan_status <> 'CLOSED' AND closed_date IS NULL))
);

-- ---------------------------------------------------------------------
-- PAYMENT: one row per monthly instalment that has fallen due.
--   ON_TIME / LATE -> money received (payment_date filled)
--   MISSED         -> nothing received yet (payment_date NULL, amount 0)
-- amount_due   = what the customer owed for that instalment (the EMI)
-- payment_amount = what was actually received
-- principal_component / interest_component = how that instalment splits
-- ---------------------------------------------------------------------
CREATE TABLE payment (
    payment_id             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    loan_id                NUMBER        NOT NULL,
    installment_no         NUMBER(4)     NOT NULL,
    due_date               DATE          NOT NULL,
    amount_due             NUMBER(15,2)  NOT NULL,
    payment_date           DATE,
    payment_amount         NUMBER(15,2) DEFAULT 0 NOT NULL,
    principal_component    NUMBER(15,2)  NOT NULL,
    interest_component     NUMBER(15,2)  NOT NULL,
    payment_status         VARCHAR2(10)  NOT NULL,
    payment_method         VARCHAR2(15),
    transaction_reference  VARCHAR2(40),
    created_at             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_payment          PRIMARY KEY (payment_id),
    CONSTRAINT fk_payment_loan     FOREIGN KEY (loan_id) REFERENCES loan(loan_id),
    CONSTRAINT uq_payment_install  UNIQUE (loan_id, installment_no),
    CONSTRAINT uq_payment_txn_ref  UNIQUE (transaction_reference),     -- NULLs allowed (missed instalments)
    CONSTRAINT ck_pay_amounts      CHECK (amount_due > 0 AND payment_amount >= 0
                                          AND principal_component >= 0 AND interest_component >= 0),
    CONSTRAINT ck_pay_status       CHECK (payment_status IN ('ON_TIME','LATE','MISSED')),
    CONSTRAINT ck_pay_method       CHECK (payment_method IN ('UPI','NACH','NET_BANKING','CHEQUE','CASH')),
    -- consistency between status, date and amount
    CONSTRAINT ck_pay_missed       CHECK (
        (payment_status = 'MISSED'  AND payment_date IS NULL AND payment_amount = 0)
     OR (payment_status = 'ON_TIME' AND payment_date IS NOT NULL AND payment_date <= due_date AND payment_amount > 0)
     OR (payment_status = 'LATE'    AND payment_date IS NOT NULL AND payment_date >  due_date AND payment_amount > 0))
);

-- ---------------------------------------------------------------------
-- INDEXES on foreign keys and frequently filtered columns.
-- (Oracle indexes PK/UNIQUE columns automatically, not FKs.)
-- ---------------------------------------------------------------------
CREATE INDEX ix_app_customer    ON loan_application (customer_id);
CREATE INDEX ix_app_branch      ON loan_application (branch_id);
CREATE INDEX ix_app_loan_type   ON loan_application (loan_type_id);
CREATE INDEX ix_app_status_date ON loan_application (application_status, application_date);
CREATE INDEX ix_loan_customer   ON loan (customer_id);
CREATE INDEX ix_loan_branch     ON loan (branch_id);
CREATE INDEX ix_loan_loan_type  ON loan (loan_type_id);
CREATE INDEX ix_loan_status     ON loan (loan_status);
CREATE INDEX ix_payment_due     ON payment (due_date);
CREATE INDEX ix_payment_status  ON payment (payment_status);

-- ---------------------------------------------------------------------
-- TRIGGERS
-- 1) Keep updated_at current automatically
-- ---------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_customer_updated_at
BEFORE UPDATE ON customer
FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
END;
/

CREATE OR REPLACE TRIGGER trg_loan_updated_at
BEFORE UPDATE ON loan
FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
END;
/

-- ---------------------------------------------------------------------
-- 2) BUSINESS RULE: a loan can only be created from an APPROVED
--    application, and must belong to the same customer/branch/type.
--    (A CHECK constraint cannot look at another table, so a trigger does it.)
-- ---------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_loan_requires_approval
BEFORE INSERT ON loan
FOR EACH ROW
DECLARE
    v_app loan_application%ROWTYPE;
BEGIN
    SELECT * INTO v_app
    FROM   loan_application
    WHERE  application_id = :NEW.application_id;

    IF v_app.application_status <> 'APPROVED' THEN
        RAISE_APPLICATION_ERROR(-20001,
            'Loan cannot be created: application ' || :NEW.application_id ||
            ' has status ' || v_app.application_status);
    END IF;

    IF v_app.customer_id  <> :NEW.customer_id
       OR v_app.branch_id <> :NEW.branch_id
       OR v_app.loan_type_id <> :NEW.loan_type_id THEN
        RAISE_APPLICATION_ERROR(-20002,
            'Loan customer/branch/loan type must match its application');
    END IF;

    IF :NEW.disbursement_date < v_app.approved_date THEN
        RAISE_APPLICATION_ERROR(-20003, 'Disbursement date cannot be before approval date');
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20004, 'Application ' || :NEW.application_id || ' does not exist');
END;
/
